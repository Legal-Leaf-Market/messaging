// Builds messaging/courier-data.js from the hand-checked suppliers, a snapshot of the Heart of
// Columbus directory, and the NDA text in setup-courier.sql. Run it after changing any of those:
//   node scripts/build-courier.mjs [path to a Heart-Of-Columbus checkout]
// Without a checkout it keeps the existing directory snapshot.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SUPPLIERS, HOC_CAPS, CAP_LABELS, AREA_MILES } from '../courier/suppliers.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'messaging/courier-data.js');
const snap = resolve(root, 'courier/hoc-snapshot.json');
const HOC_ORIGIN = 'https://heartofcolumbus.netlify.app';

const hocPath = process.argv[2];
if (hocPath) {
  const m = await import(pathToFileURL(resolve(hocPath, 'src/data/directory.mjs')).href);
  const cats = Object.fromEntries(m.CATEGORIES.map((c) => [c.slug, c.label]));
  const subs = Object.fromEntries(m.CATEGORIES.flatMap((c) => c.subs.map((s) => [s.slug, s.label])));
  const rows = m.directory.map((b) => ({
    s: b.slug, n: b.name, c: cats[b.cat] || b.cat, u: subs[b.sub] || '', t: b.type || '', a: b.address || '',
    p: b.phone || '', w: b.website || '', l: b.ll || null,
  }));
  writeFileSync(snap, JSON.stringify({ taken: new Date().toISOString().slice(0, 10), rows }));
}
if (!existsSync(snap)) throw new Error('No Heart of Columbus snapshot yet. Pass a checkout path.');
const hoc = JSON.parse(readFileSync(snap, 'utf8'));

const sql = readFileSync(resolve(root, 'setup-courier.sql'), 'utf8');
const nda = sql.match(/values \('([^']+)', \$nda\$([\s\S]*?)\$nda\$, true\)/);
if (!nda) throw new Error('NDA text not found in setup-courier.sql');

// Rows from outside research replace a hand-checked row of the same name and stay marked "verify".
const extraPath = resolve(root, 'courier/catalog-additions.json');
const extras = existsSync(extraPath) ? JSON.parse(readFileSync(extraPath, 'utf8')) : [];
// Same business if the names match once "Inc.", "Co." and anything in brackets are dropped.
const key = (n) => n.toLowerCase().replace(/\(.*?\)/g, '').replace(/\b(inc|co|llc|corp|corporation|company|the)\b/g, '').replace(/[^a-z]/g, '');
const same = (a, b) => { const x = key(a), y = key(b); return x === y || x.startsWith(y) || y.startsWith(x); };
const suppliers = SUPPLIERS.filter((x) => !extras.some((e) => same(e.name, x.name))).concat(extras);

const data = {
  hocOrigin: HOC_ORIGIN, hocTaken: hoc.taken, suppliers, hocCaps: HOC_CAPS, capLabels: CAP_LABELS, areaMiles: AREA_MILES, hoc: hoc.rows,
  nda: { version: nda[1], body: nda[2] },
};
writeFileSync(out, '// Generated by scripts/build-courier.mjs. Do not edit by hand.\nwindow.CC_DATA=' + JSON.stringify(data) + ';\n');
console.log(`courier-data.js: ${suppliers.length} suppliers, ${hoc.rows.length} Heart of Columbus listings`);
